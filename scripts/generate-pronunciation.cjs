// Build the fixed Japanese vocabulary list from the actual game content.
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const load = file => {
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports });
  return exports;
};
const { words, lessons } = load('src/game/learning.ts');
const phrases = new Map();
const normalize = text => text.replace(/[\s。！!？?、，,.「」“”]/g, '');
const add = (text, reading = text) => {
  if (!/[ぁ-龯]/u.test(text)) return;
  const key = normalize(text);
  if (!phrases.has(key)) phrases.set(key, { text: key, reading });
};
for (const word of words) add(word.japanese, word.id === 'object' ? 'お' : word.reading);
for (const lesson of lessons) for (const question of lesson.questions) {
  if (question.japanese) add(question.japanese);
  question.answers.forEach(answer => add(answer));
}
for (const drink of ['コーヒー', 'お茶', 'お水']) {
  add(drink);
  for (const count of ['一つ', '二つ']) add(`${drink}を${count}ください。`);
}
for (const text of ['の', 'に', 'ようこそ', 'よろしくお願いします', '駅', 'コンビニ', '無料', 'みずをください', '450円です。ありがとうございます', '200円です。ありがとうございます']) add(text);
for (const [text, reading] of [
  ['零円です', 'れいえんです'], ['三百五十円です', 'さんびゃくごじゅうえんです'],
  ['四百五十円です', 'よんひゃくごじゅうえんです'], ['七百円です', 'ななひゃくえんです'],
  ['九百円です', 'きゅうひゃくえんです'],
]) add(text, reading);
const existing = load('src/game/voiceClips.ts').voiceClips;
let next = Math.max(0,...Object.values(existing).map(path => Number(path.match(/ja-(\d+)/)?.[1] ?? 0)));
const entries = [...phrases.values()].map(entry => ({ ...entry, file: existing[entry.text]?.split('/').pop() ?? 'ja-'+String(++next).padStart(2,'0')+'.mp3' }));
fs.writeFileSync('scripts/pronunciation-phrases.json', JSON.stringify(entries, null, 2) + '\n');
const manifest = Object.fromEntries(entries.map(entry => [entry.text, `/audio/ja/${entry.file}`]));
for (const word of words) manifest[normalize(word.reading)] = manifest[normalize(word.japanese)];
fs.writeFileSync('src/game/voiceClips.ts', `// Generated by scripts/generate-pronunciation.cjs. Voice provenance: public/audio/README.md.\nexport const voiceClips: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`${entries.length} Japanese pronunciation clips in catalog.`);
